// Función auxiliar para buscar traducciones de palabras o frases
export function lookupTranslation(text) {
  if (!text) return null;
  const clean = text.trim().toLowerCase().replace(/[.,/#!$%^&*;:{}=\-_`~()?"']/g, "");
  
  // Coincidencia directa
  if (BILINGUAL_DICTIONARY[clean]) {
    return { term: clean, ...BILINGUAL_DICTIONARY[clean] };
  }

  // Búsqueda por subfrase o palabra compuesta
  for (const [key, val] of Object.entries(BILINGUAL_DICTIONARY)) {
    if (clean.includes(key) || key.includes(clean)) {
      return { term: key, ...val };
    }
  }

  return null;
}
